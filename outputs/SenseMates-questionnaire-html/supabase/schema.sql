-- SenseMates questionnaire storage for Supabase
-- Run this entire file once in Supabase > SQL Editor.

create table if not exists public.sensemates_responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  survey_version text not null default '2026-10',
  nickname text not null check (char_length(nickname) between 1 and 24),
  role text not null,
  gender text not null,
  grade text not null,
  major text not null check (char_length(major) between 1 and 50),
  buddy text not null,
  answers jsonb not null check (jsonb_typeof(answers) = 'array')
);

create index if not exists sensemates_responses_created_at_idx
  on public.sensemates_responses (created_at desc);

alter table public.sensemates_responses enable row level security;

-- Visitors may submit a response, but they cannot read, edit, or delete responses.
revoke all on table public.sensemates_responses from anon, authenticated;
grant insert on table public.sensemates_responses to anon, authenticated;
revoke all on sequence public.sensemates_responses_id_seq from anon, authenticated;
grant usage on sequence public.sensemates_responses_id_seq to anon, authenticated;

drop policy if exists "Anyone can submit a SenseMates response"
  on public.sensemates_responses;

create policy "Anyone can submit a SenseMates response"
  on public.sensemates_responses
  for insert
  to anon, authenticated
  with check (
    survey_version = '2026-10'
    and char_length(nickname) between 1 and 24
    and char_length(major) between 1 and 50
    and jsonb_array_length(answers) = 10
  );
